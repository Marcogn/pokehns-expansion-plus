#!/usr/bin/env python3
"""Generate src/data/pokemon/owe_temperaments.h from the user's temperament table.

Input: docs/plans/overworld-encounters/temperaments.json (exported from the
"Indole dei selvatici" page, see docs/plans/overworld-encounters.md) and the
#if P_FAMILY_X blocks of src/data/pokemon/species_info/gen_N_families.h.

Every species of a family listed in the table gets the family's temperament,
wild or not (Pidgeot = Pidgey's), unless the table names it as an exception;
an exception also covers that species' Mega and Gigantamax forms. Species of
families missing from the table stay NEUTRO, which is temperament 0, so the
generated array only lists the others.

Run from the repo root after changing temperaments.json:
    python3 tools/owe_temperaments.py
"""
import json
import os
import re
import sys

TABLE = 'docs/plans/overworld-encounters/temperaments.json'
OUT = 'src/data/pokemon/owe_temperaments.h'

# Order of the weights in temperaments.json -> behaviour enum of
# include/wild_encounter_ow.h (enum OverworldWildEncounterBehaviors).
BEHAVIOURS = {
    'guarda': 'OWE_WATCH_PLAYER_NORMAL',
    'gira': 'OWE_IGNORE_PLAYER',
    'avvicina': 'OWE_APPROACH_PLAYER_SLOW',
    'insegue': 'OWE_CHASE_PLAYER_SLOW',
    'scappa': 'OWE_FLEE_PLAYER_NORMAL',
    'sparisce': 'OWE_DESPAWN_ON_NOTICE',
}
# NEUTRO first: it is the zero value, the temperament of every unlisted species.
TEMPERAMENTS = ['NEUTRO', 'TIMIDO', 'AGGRESSIVO', 'CURIOSO', 'PLACIDO', 'SFUGGENTE']
FORM_SUFFIXES = ('_MEGA', '_MEGA_X', '_MEGA_Y', '_GMAX')


def families():
    """species -> family, in file order, from the #if P_FAMILY_X blocks."""
    fam = {}
    for g in range(1, 10):
        path = f'src/data/pokemon/species_info/gen_{g}_families.h'
        if not os.path.exists(path):
            continue
        cur = None
        for line in open(path):
            m = re.match(r'#if P_FAMILY_(\w+)', line)
            if m:
                cur = m.group(1)
            m = re.match(r'\s*\[SPECIES_(\w+)\]\s*=', line)
            if m and cur:
                fam[m.group(1)] = cur
    return fam


def main():
    table = json.load(open(TABLE))
    if list(table['behaviours']) != list(BEHAVIOURS):
        sys.exit(f'unexpected behaviour order in {TABLE}: {table["behaviours"]}')
    if sorted(table['profiles']) != sorted(TEMPERAMENTS):
        sys.exit(f'unexpected temperaments in {TABLE}: {sorted(table["profiles"])}')

    fam = families()
    known_fams = set(fam.values())
    errors = [f'family {f} has no P_FAMILY block' for f in table['families'] if f not in known_fams]
    errors += [f'species {s} ({f}) has no gSpeciesInfo entry'
               for f, v in table['families'].items() for s in v['species'] if s not in fam]
    if errors:
        sys.exit('\n'.join(errors))

    result = {}
    for species, f in fam.items():
        entry = table['families'].get(f)
        if entry is None:
            continue
        temperament = entry['profile']
        exceptions = entry['species']
        if species in exceptions:
            temperament = exceptions[species]
        else:
            for base, t in exceptions.items():
                if any(species == base + suffix for suffix in FORM_SUFFIXES):
                    temperament = t
        if temperament != 'NEUTRO':
            result[species] = temperament

    lines = [
        '// Generated by tools/owe_temperaments.py from',
        f'// {TABLE}: do not edit by hand.',
        '',
        '// Weights of each behaviour per temperament, rolled when an OWE spawns.',
        'static const u8 sOWETemperamentWeights[OWE_TEMPERAMENT_COUNT][OWE_SPECIES_BEHAVIOR_COUNT] =',
        '{',
    ]
    for t in TEMPERAMENTS:
        weights = table['profiles'][t]
        lines.append(f'    [OWE_TEMPERAMENT_{t}] =')
        lines.append('    {')
        for key, enum in BEHAVIOURS.items():
            lines.append(f'        [{enum}] = {weights[key]},')
        lines.append('    },')
    lines += [
        '};',
        '',
        '// Species not listed are OWE_TEMPERAMENT_NEUTRO (0).',
        'static const u8 sOWESpeciesTemperament[NUM_SPECIES] =',
        '{',
    ]
    for species in fam:
        if species in result:
            lines.append(f'    [SPECIES_{species}] = OWE_TEMPERAMENT_{result[species]},')
    lines.append('};')
    open(OUT, 'w').write('\n'.join(lines) + '\n')

    counts = {t: list(result.values()).count(t) for t in TEMPERAMENTS[1:]}
    print(f'{OUT}: {len(result)} species not NEUTRO {counts}')


if __name__ == '__main__':
    main()
