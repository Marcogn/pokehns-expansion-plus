#!/usr/bin/env python3
"""Write the version shown in the save menu as a C header.

    version_header.py VERSION out.h

VERSION is HNS_VERSION, the same value tools/version_strip.py draws under
PRESS START, and it is spelled the same way: a lowercase 'v', the rest
uppercase (v2.0.6.PLUS.7), so the two screens agree. An empty VERSION (a
clone without tags, like the build CI) writes the fallback "dev build".
The file is rewritten only when its text changes, so a build that does not
change the version recompiles nothing.
"""
import re
import sys

FALLBACK = 'dev build'


def main():
    if len(sys.argv) != 3:
        sys.exit('usage: version_header.py VERSION out.h')
    raw, path = sys.argv[1:]
    if raw:
        text = 'v' + raw[1:].upper() if raw[:1] in 'vV' else 'v' + raw.upper()
    else:
        text = FALLBACK
    # It ends up in a C string the game's charmap has to know: keep to the
    # characters a version tag uses. The save menu has 112 px for it in the
    # narrow font, about 5 px a character: past 20 it would run off the window.
    if not re.fullmatch(r'[A-Za-z0-9. +_-]+', text) or len(text) > 20:
        sys.exit(f'version_header.py: cannot show version {text!r} in the save menu')
    content = ('// Generated by tools/version_header.py from HNS_VERSION. Do not edit.\n'
               f'#define HNS_VERSION_TEXT "{text}"\n')
    try:
        with open(path) as f:
            if f.read() == content:
                return
    except FileNotFoundError:
        pass
    with open(path, 'w') as f:
        f.write(content)


if __name__ == '__main__':
    main()
